import { describe, expect, it } from 'vitest'
import { bpmBucket, bpmDistancePct, bpmRelation, bpmScore, bpmText } from '../../src/engine/bpm'
import { allGenres, BEATPORT_GENRES, DEFAULT_GENRE_TABLE, familyOf, GENRE_BPM, genreRelation, genreScore, isOpenFormat, normalizeGenre } from '../../src/engine/genres'
import { clampEnergy, energyScore, energyText, GENRE_BASE_ENERGY, heuristicEnergy } from '../../src/engine/energy'

describe('BPM model', () => {
  it('half/double time distances', () => {
    expect(bpmDistancePct(87, 174)).toBe(0)
    expect(bpmDistancePct(174, 87)).toBe(0)
    expect(bpmDistancePct(64, 128)).toBe(0)
    expect(bpmDistancePct(124, 126)).toBeCloseTo(1.613, 2)
    expect(bpmDistancePct(0, 120)).toBe(Infinity)
    expect(bpmRelation(128, 64)).toBe('half')
    expect(bpmRelation(64, 128)).toBe('double')
    expect(bpmRelation(124, 125)).toBe('normal')
  })
  it('score table', () => {
    expect(bpmScore(124, 125)).toBe(1)
    expect(bpmScore(124, 127)).toBe(0.85)
    expect(bpmScore(124, 130)).toBe(0.6)
    expect(bpmScore(124, 131)).toBe(0.4)
    expect(bpmScore(124, 140)).toBe(0.05)
    expect(bpmScore(124, 131, 5)).toBe(0.05)
    expect(bpmScore(87, 174)).toBe(1)
    expect(bpmScore(null, 120)).toBe(0.5)
  })
  it('buckets and text', () => {
    expect(bpmBucket(124, 125)).toBe('b0')
    expect(bpmBucket(124, 127)).toBe('b1')
    expect(bpmBucket(124, 130)).toBe('b2')
    expect(bpmBucket(124, 140)).toBe('b3')
    expect(bpmBucket(null, 140)).toBe('b?')
    expect(bpmText(124, 125)).toBe('BPM +1')
    expect(bpmText(125, 123)).toBe('BPM −2')
    expect(bpmText(124, 124)).toBe('BPM =')
    expect(bpmText(124, 124.5)).toBe('BPM +0.5')
    expect(bpmText(64, 128)).toBe('BPM 2×')
    expect(bpmText(128, 64)).toBe('BPM ½×')
    expect(bpmText(120, 140)).toBe('BPM +20 ✕')
    expect(bpmText(null, 1)).toBe('BPM ?')
  })
})

describe('genres', () => {
  it('normalizes rekordbox free text', () => {
    expect(normalizeGenre('tech house')).toBe('Tech House')
    expect(normalizeGenre(' Melodic Techno ')).toBe('Melodic House & Techno')
    expect(normalizeGenre('Melodic House&Techno')).toBe('Melodic House & Techno')
    expect(normalizeGenre('Nu Disco/Disco')).toBe('Nu Disco / Disco')
    expect(normalizeGenre('TECHNO')).toBe('Techno (Peak Time / Driving)')
    expect(normalizeGenre('Hip Hop')).toBe('Hip-Hop')
    expect(normalizeGenre('Gqom')).toBe('Gqom')
    expect(normalizeGenre('')).toBeNull()
    expect(normalizeGenre(null)).toBeNull()
  })
  it('families and open format', () => {
    expect(familyOf('Deep House')).toBe('house')
    expect(familyOf('Hard Techno')).toBe('techno')
    expect(familyOf('Gqom')).toBe('other')
    expect(familyOf(null)).toBe('unknown')
    expect(isOpenFormat('Pop')).toBe(true)
    expect(isOpenFormat('House')).toBe(false)
    expect(isOpenFormat(null)).toBe(false)
  })
  it('scores per ENGINE.md §3', () => {
    expect(genreRelation('House', 'House')).toEqual({ link: 'same', score: 1 })
    expect(genreScore('House', 'Deep House')).toBe(0.75)
    expect(genreScore('Melodic House & Techno', 'Progressive House')).toBe(0.6)
    expect(genreScore('Progressive House', 'Melodic House & Techno')).toBe(0.6)
    expect(genreScore('Afro House', 'Amapiano')).toBe(0.2)
    expect(genreScore('Organic House / Downtempo', 'Amapiano')).toBe(0.6)
    expect(genreScore('Pop', 'Techno (Peak Time / Driving)')).toBe(0.5)
    expect(genreScore('Drum & Bass', 'Tech House')).toBe(0.2)
    expect(genreScore(null, 'House')).toBe(0.5)
    expect(genreScore('Gqom', 'House')).toBe(0.5)
  })
  it('every Beatport genre has a family and a BPM range', () => {
    expect(BEATPORT_GENRES).toHaveLength(19)
    for (const g of BEATPORT_GENRES) {
      expect(familyOf(g)).not.toBe('other')
      expect(GENRE_BPM[g]).toBeDefined()
    }
    for (const g of allGenres(DEFAULT_GENRE_TABLE)) expect(GENRE_BASE_ENERGY[g], g).toBeDefined()
  })
})

describe('energy', () => {
  it('heuristic: base by genre, BPM ±1, banger +1', () => {
    expect(heuristicEnergy({ genre: 'Deep House', bpm: 121 })).toBe(4)
    expect(heuristicEnergy({ genre: 'Deep House', bpm: 126 })).toBe(5)
    expect(heuristicEnergy({ genre: 'Deep House', bpm: 110 })).toBe(3)
    expect(heuristicEnergy({ genre: 'Hard Techno', bpm: 170, tags: ['banger'] })).toBe(10)
    expect(heuristicEnergy({ genre: null, bpm: null })).toBe(5)
    expect(clampEnergy(14)).toBe(10)
    expect(clampEnergy(-1)).toBe(1)
  })
  it('direction rules', () => {
    expect(energyScore(5, 6, 'up')).toBe(1)
    expect(energyScore(5, 7, 'up')).toBe(1)
    expect(energyScore(5, 5, 'up')).toBe(0.8)
    expect(energyScore(5, 8, 'up')).toBe(0.6)
    expect(energyScore(5, 9, 'up')).toBe(0.3)
    expect(energyScore(5, 4, 'up')).toBe(0.6)
    expect(energyScore(5, 3, 'up')).toBe(0.2)
    expect(energyScore(6, 3, 'up')).toBe(0.05)
    expect(energyScore(6, 5, 'down')).toBe(1)
    expect(energyScore(6, 6, 'down')).toBe(0.8)
    expect(energyScore(6, 3, 'down')).toBe(0.6)
    expect(energyScore(7, 3, 'down')).toBe(0.2)
    expect(energyScore(6, 7, 'down')).toBe(0.6)
    expect(energyScore(6, 9, 'down')).toBe(0.2)
    expect(energyScore(6, 6, 'flat')).toBe(1)
    expect(energyScore(6, 7, 'flat')).toBe(0.9)
    expect(energyScore(6, 8, 'flat')).toBe(0.6)
    expect(energyScore(6, 9, 'flat')).toBe(0.3)
    expect(energyScore(6, 3, 'flat')).toBe(0.05)
    expect(energyScore(6, 7)).toBe(1)
    expect(energyScore(6, 8)).toBe(0.85)
    expect(energyScore(6, 9)).toBe(0.6)
    expect(energyScore(5, 9)).toBe(0.4)
    expect(energyScore(9, 5)).toBe(0.05)
  })
  it('text', () => {
    expect(energyText(5, 6, 1)).toBe('energy +1 ✓')
    expect(energyText(6, 3, 0.05)).toBe('energy −3 ✕')
    expect(energyText(6, 6, 0.6)).toBe('energy ±0')
  })
})
